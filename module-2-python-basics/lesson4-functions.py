# Lesson 4: Functions

# 1. Explanation
# A function is a reusable block of code that performs a specific task.
# Functions help make programs more organized and avoid repeating code.


# 2. Key Vocabulary
# Function - a reusable block of code that performs a task.
# Parameter - a variable listed inside the function definition.
# Argument - the actual value passed to a parameter.
# Return value - the result that a function sends back using return.


# 3. My Own Example

def greet(name):
    message = "Hello, " + name
    return message

result = greet("Justin")
print(result)


